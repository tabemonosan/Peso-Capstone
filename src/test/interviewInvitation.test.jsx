import { cleanup, fireEvent, render, screen, within, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import EmployerInterviewPanel from '../components/EmployerInterviewPanel'
import { philippineDateTimeInput } from '../../shared/interviewInvitation.js'

beforeEach(() => vi.stubGlobal('fetch', vi.fn(async (url, options) => ({ ok: true, json: async () => url.endsWith('/api/profile') ? { establishmentAddress: { city: 'Manito', barangay: 'Nagotgot', province: 'Albay' } } : options?.method === 'POST' ? { id: 'interview1', ...JSON.parse(options.body), status: 'invited' } : null }))))
afterEach(() => { cleanup(); vi.unstubAllGlobals() })
async function openForm() {
  render(<EmployerInterviewPanel token="employer" referralId="referral1" />)
  fireEvent.click(screen.getByRole('button', { name: 'Invite to interview' }))
  return screen.findByRole('dialog', { name: 'Interview invitation' })
}
function fill(dialog) {
  fireEvent.change(within(dialog).getByLabelText(/Interview date and time/), { target: { value: philippineDateTimeInput(new Date(Date.now() + 86400000)) } })
}
describe('interview invitation date and location', () => {
  it('keeps the invitation unchanged when confirmation is cancelled', async () => {
    const dialog = await openForm()
    fill(dialog)
    fireEvent.change(within(dialog).getByLabelText(/Message to applicant/), { target: { value: 'Bring your resume.' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Send invitation' }))
    const confirmation = await screen.findByRole('alertdialog', { name: 'Send interview invitation?' })
    expect(within(confirmation).getByText('Nagotgot, Manito, Albay')).toBeInTheDocument()
    expect(within(confirmation).getByText('Bring your resume.')).toBeInTheDocument()
    fireEvent.click(within(confirmation).getByRole('button', { name: 'Cancel' }))
    expect(within(dialog).getByLabelText(/Message to applicant/)).toHaveValue('Bring your resume.')
    expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(false)
    expect(screen.queryByRole('alertdialog')).not.toBeInTheDocument()
  })

  it('disables past date/time values and hides address fields supplied by the registered NSRP', async () => {
    const dialog = await openForm()
    expect(within(dialog).getByLabelText(/Message to applicant/)).toHaveAttribute('maxlength', '50')
    const date = within(dialog).getByLabelText(/Interview date and time/)
    expect(+new Date(`${date.min}+08:00`)).toBeGreaterThan(Date.now())
    fireEvent.change(date, { target: { value: '2020-01-01T10:00' } })
    expect(date.validity.rangeUnderflow).toBe(true)
    for (const label of [/Municipality \/ city/, /Province/, /Barangay/, /Landmark/]) expect(within(dialog).queryByLabelText(label)).not.toBeInTheDocument()
  })
  it('submits a future Philippine time and required address without a landmark', async () => {
    const dialog = await openForm()
    fill(dialog)
    fireEvent.click(within(dialog).getByRole('button', { name: 'Send invitation' }))
    const confirmation = await screen.findByRole('alertdialog')
    expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(false)
    fireEvent.click(within(confirmation).getByRole('button', { name: 'Confirm send' }))
    await waitFor(() => expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(true))
    const [, options] = fetch.mock.calls.find(([, options]) => options?.method === 'POST')
    expect(JSON.parse(options.body)).toMatchObject({ city: 'Manito', barangay: 'Nagotgot', province: 'Albay', landmark: '', location: 'Nagotgot, Manito, Albay' })
    expect(+new Date(JSON.parse(options.body).scheduledAt)).toBeGreaterThan(Date.now())
    await waitFor(() => expect(screen.queryByRole('dialog', { name: 'Interview invitation' })).not.toBeInTheDocument())
    expect(screen.getByText('Nagotgot, Manito, Albay')).toBeInTheDocument()
  })
  it('refreshes the registered address when sending instead of relying on the hidden form values', async () => {
    const dialog = await openForm()
    fill(dialog)
    const original = fetch.getMockImplementation()
    fetch.mockImplementation(async (url, options) => url.endsWith('/api/profile') ? { ok: true, json: async () => ({ establishmentAddress: { city: 'Oas', province: 'Albay', barangay: 'Calpi' } }) } : original(url, options))
    fireEvent.click(within(dialog).getByRole('button', { name: 'Send invitation' }))
    const confirmation = await screen.findByRole('alertdialog')
    expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(false)
    fireEvent.click(within(confirmation).getByRole('button', { name: 'Confirm send' }))
    await waitFor(() => expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(true))
    const body = JSON.parse(fetch.mock.calls.find(([, options]) => options?.method === 'POST')[1].body)
    expect(body).toMatchObject({ city: 'Oas', barangay: 'Calpi', province: 'Albay', useRegisteredAddress: true, location: 'Calpi, Oas, Albay' })
  })
  it('recovers the registered barangay and landmark from a legacy address and includes them in an online invitation', async () => {
    const original = fetch.getMockImplementation()
    fetch.mockImplementation(async (url, options) => url.endsWith('/api/profile') ? { ok: true, json: async () => ({ profile: { location: 'Brgy. Nagotgot, Manito, Albay, Landmark: near the hall' } }) } : original(url, options))
    const dialog = await openForm()
    fill(dialog)
    fireEvent.change(within(dialog).getByLabelText('Mode'), { target: { value: 'Online' } })
    fireEvent.change(within(dialog).getByLabelText('Meeting link *'), { target: { value: 'https://example.com/interview' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Send invitation' }))
    const confirmation = await screen.findByRole('alertdialog')
    expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(false)
    fireEvent.click(within(confirmation).getByRole('button', { name: 'Confirm send' }))
    await waitFor(() => expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(true))
    const body = JSON.parse(fetch.mock.calls.find(([, options]) => options?.method === 'POST')[1].body)
    expect(body.location).toBe('https://example.com/interview | Nagotgot, Manito, Albay, Landmark: near the hall')
  })
  it('explains a missing registration address before opening the invitation form', async () => {
    fetch.mockResolvedValue({ ok: true, json: async () => ({}) })
    render(<EmployerInterviewPanel token="employer" referralId="referral1" />)
    fireEvent.click(screen.getByRole('button', { name: 'Invite to interview' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Update your NSRP registration address')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
  it('rejects a typed past time even if browser validation is bypassed', async () => {
    const dialog = await openForm()
    fill(dialog)
    fireEvent.change(within(dialog).getByLabelText(/Interview date and time/), { target: { value: '2020-01-01T10:00' } })
    fireEvent.submit(within(dialog).getByRole('button', { name: 'Send invitation' }).closest('form'))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('Choose a future interview time')
    expect(fetch.mock.calls.some(([, options]) => options?.method === 'POST')).toBe(false)
  })
})
