import { useState } from 'react'
import { fireEvent, render, screen } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import JobPostingFields from '../components/JobPostingFields'
import { emptyJobPosting } from '../../shared/jobPosting.js'
function Form({ suggestions = ['Excel'] }) {
  const [value, setValue] = useState(emptyJobPosting)
  const [errors, setErrors] = useState({})
  return <form><JobPostingFields value={value} onChange={setValue} categories={[]} suggestions={suggestions} errors={errors} setErrors={setErrors} /></form>
}
describe('job request fields', () => {
  it('reports errors on blur, toggles remote fields, formats money and disables negotiable inputs', () => {
    render(<Form />)
    fireEvent.blur(screen.getByLabelText('Description *'))
    expect(screen.getByText('Describe the responsibilities and role.')).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Location type *'), { target: { value: 'Remote' } })
    expect(screen.queryByLabelText('City/Municipality *')).not.toBeInTheDocument()
    const min = screen.getByLabelText('Salary Min (₱) *')
    fireEvent.change(min, { target: { value: '25000' } })
    fireEvent.blur(min)
    expect(min).toHaveValue('25,000')
    fireEvent.click(screen.getByLabelText('Salary is negotiable'))
    expect(min).toBeDisabled()
    expect(screen.getByLabelText('Salary Max (₱)')).toBeDisabled()
  })
  it('strips non-digits on typing and paste and reports the range error under maximum salary', () => {
    render(<Form />)
    const min = screen.getByLabelText('Salary Min (\u20b1) *')
    fireEvent.focus(min)
    fireEvent.change(min, { target: { value: '15abc000' } })
    expect(min).toHaveValue('15000')
    min.setSelectionRange(0, min.value.length)
    fireEvent.paste(min, { clipboardData: { getData: () => '\u20b120,000 letters' } })
    expect(min).toHaveValue('20000')
    fireEvent.blur(min)
    expect(min).toHaveValue('20,000')
    const max = screen.getByLabelText('Salary Max (\u20b1) *')
    fireEvent.change(max, { target: { value: '15000' } })
    fireEvent.blur(max)
    expect(max).toHaveAttribute('aria-invalid', 'true')
    expect(max.parentElement).toHaveTextContent('Maximum salary must be at least the minimum.')
    const slots = screen.getByLabelText('Available slots *')
    fireEvent.change(slots, { target: { value: 'a3e2-+' } })
    expect(slots).toHaveValue('32')
  })
  it('adds multiple clicked suggestions immediately and keeps the light list open', () => {
    render(<Form suggestions={['Excel', 'Communication', 'Data Entry']} />)
    const input = screen.getByLabelText('Required skills *')
    fireEvent.focus(input)
    const first = screen.getByRole('option', { name: 'Excel' })
    fireEvent.click(first)
    expect(screen.getByRole('button', { name: 'Remove Excel' })).toBeInTheDocument()
    expect(first).toHaveAttribute('aria-selected', 'true')
    fireEvent.click(screen.getByRole('option', { name: 'Communication' }))
    expect(screen.getByRole('button', { name: 'Remove Communication' })).toBeInTheDocument()
    expect(screen.getByRole('listbox', { name: 'Skill suggestions' })).toHaveAttribute('aria-multiselectable', 'true')
    expect(screen.queryByRole('button', { name: 'Add', exact: true })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('option', { name: 'Excel' }))
    expect(screen.queryByRole('button', { name: 'Remove Excel' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Remove Communication' })).toBeInTheDocument()
  })
  it('searches suggestions and selects by keyboard without submitting the form', () => {
    render(<Form suggestions={['Excel', 'Communication']} />)
    const input = screen.getByLabelText('Required skills *')
    fireEvent.focus(input)
    fireEvent.change(input, { target: { value: 'comm' } })
    expect(screen.queryByRole('option', { name: 'Excel' })).not.toBeInTheDocument()
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(screen.getByRole('button', { name: 'Remove Communication' })).toBeInTheDocument()
    fireEvent.change(input, { target: { value: 'Custom skill' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(screen.getByRole('button', { name: 'Remove Custom skill' })).toBeInTheDocument()
    fireEvent.keyDown(input, { key: 'Escape' })
    expect(screen.queryByRole('listbox', { name: 'Skill suggestions' })).not.toBeInTheDocument()
  })
  it('adds/removes unique skill chips and excludes private notes from the preview', () => {
    render(<Form />)
    const skill = screen.getByLabelText('Required skills *')
    fireEvent.change(skill, { target: { value: 'Excel' } })
    fireEvent.keyDown(skill, { key: 'Enter' })
    expect(screen.getByRole('button', { name: 'Remove Excel' })).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Notes to PESO Admin (optional, private)'), { target: { value: 'Private admin note' } })
    fireEvent.click(screen.getByRole('button', { name: 'Preview posting' }))
    const preview = screen.getByRole('article', { name: 'Job seeker preview' })
    expect(preview).toHaveTextContent('Skills: Excel')
    expect(preview).not.toHaveTextContent('Private admin note')
    fireEvent.click(screen.getByRole('button', { name: 'Remove Excel' }))
    expect(screen.queryByRole('button', { name: 'Remove Excel' })).not.toBeInTheDocument()
  })
})
