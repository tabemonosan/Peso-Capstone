export function matchLocation(city, province) {
  if (typeof city !== 'string' || typeof province !== 'string') return null
  const name = Object.keys(PH_LOCATIONS).find((item) => item.toLowerCase() === city.trim().replace(/\s+/g, ' ').toLowerCase())
  return name && province.trim().toLowerCase() === 'albay' ? { city: name, province: 'Albay' } : null
}

export function provinceForCity(city) {
  return Object.keys(PH_LOCATIONS).some((item) => item.toLowerCase() === String(city || '').trim().toLowerCase()) ? 'Albay' : ''
}

// Accept older applicant records that omitted the "City" suffix.
export function applicantCityName(city) {
  const value = String(city || '').trim().toLowerCase()
  return Object.keys(PH_LOCATIONS).find((name) => name.toLowerCase() === value
    || name.toLowerCase().replace(/ city$/, '') === value) || ''
}

export function validateApplicantLocation(input = {}, { barangay = true } = {}) {
  const errors = {}
  const city = applicantCityName(input.addressCity)
  if (input.addressProvince && String(input.addressProvince).trim().toLowerCase() !== 'albay') {
    errors.addressProvince = 'Select an address in Albay.'
  }
  if (input.addressCity && !city) errors.addressCity = 'Select a city or municipality in Albay.'
  if (barangay && input.addressBarangay && (!city || !PH_LOCATIONS[city].some((name) =>
    name.toLowerCase() === String(input.addressBarangay).trim().toLowerCase()))) {
    errors.addressBarangay = 'Select a barangay belonging to the selected city or municipality.'
  }
  return errors
}

// City/province labels contain commas; serialize these as an array so filters
// never mistake a province for a second selected location. Old URLs still work.
// Saved job filters may still contain a full barangay/city/province address.
// Use its municipality so the filter includes every barangay in that place.
export function normalizeCityFilters(values = []) {
  return [...new Set(values.filter(value => typeof value === 'string').map(value =>
    parseStoredLocation(value)?.city || applicantCityName(value) || value.trim()
  ).filter(Boolean))]
}

export function encodeLocationFilters(values) {
  return values.some((value) => value.includes(',')) ? JSON.stringify(values) : values.join(',')
}

export function decodeLocationFilters(value) {
  if (Array.isArray(value)) return value.flatMap(decodeLocationFilters).slice(0, 50)
  if (typeof value !== 'string') return []
  if (parseStoredLocation(value)) return [value]
  if (value.startsWith('[')) {
    try {
      const parsed = JSON.parse(value)
      return Array.isArray(parsed) ? parsed.filter((entry) => typeof entry === 'string').slice(0, 50) : []
    } catch { return [] }
  }
  return value.split(',').map((entry) => entry.trim()).filter(Boolean).slice(0, 50)
}

// Read only exact known cities or the city/province suffix produced by signup.
export function parseStoredLocation(location) {
  if (typeof location !== 'string') return null
  const address = location.split(/,\s*Landmark\s*:/i)[0].trim()
  const parts = address.split(',').map((part) => part.trim()).filter(Boolean)
  return parts.length >= 2
    ? matchLocation(parts.at(-2), parts.at(-1))
    : matchLocation(address, provinceForCity(address))
}

// Resolve registered addresses across current and legacy employer records.
// Legacy text must be an exact known city, or end in a known city/province
// pair from the signup serializer. Never infer a place from a street/landmark.
export function getEmployerAddress(employer = {}, request = {}) {
  const profile = employer.profile || {}
  const details = request?.registrationDetails || {}
  for (const [city, province] of [
    [employer.establishmentAddress?.city, employer.establishmentAddress?.province],
    [details.cityMunicipality, details.province],
    [profile.addressCity || profile.city, profile.addressProvince || profile.province],
  ]) {
    const place = matchLocation(city, province)
    if (place) return place
  }
  for (const location of [profile.location, request?.location]) {
    const place = parseStoredLocation(location)
    if (place) return place
  }
  return {}
}

export function matchBarangay(city, barangay) {
  const raw = String(barangay || '').trim().toLowerCase()
  const value = raw.replace(/^(?:brgy\.?|barangay)\s+/i, '')
  return (PH_LOCATIONS[city] || []).find((name) => name.toLowerCase() === raw || name.toLowerCase() === value) || ''
}

export function storedBarangay(location, city) {
  const place = parseStoredLocation(location)
  if (!place || place.city !== city) return ''
  const parts = location.split(/,\s*Landmark\s*:/i)[0].split(',').map((part) => part.trim()).filter(Boolean)
  return parts.length >= 3 ? matchBarangay(city, parts.at(-3)) : ''
}

export function getEmployerJobAddress(employer = {}, request = {}) {
  const place = getEmployerAddress(employer, request)
  if (!place.city) return place
  const barangay = matchBarangay(place.city, employer.establishmentAddress?.barangay)
    || matchBarangay(place.city, request?.registrationDetails?.barangay)
    || matchBarangay(place.city, employer.profile?.barangay)
    || storedBarangay(employer.profile?.location || '', place.city)
    || storedBarangay(request?.location || '', place.city)
  return barangay ? { ...place, barangay } : place
}
